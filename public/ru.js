/* bo'sh joylarni saqlab tarjima qiladi; topilmasa asl matn qoladi */
window.ruText = function (s) {
  const m = /^(\s*)([\s\S]*?)(\s*)$/.exec(s), key = m[2].replace(/\s+/g, " ");
  if (!key) return s;
  if (Object.prototype.hasOwnProperty.call(RU, key)) return m[1] + RU[key] + m[3];
  for (const [rx, fn] of RU_RX) { const x = rx.exec(key); if (x) return m[1] + fn(...x) + m[3]; }
  return s;
};
